    ACCY_OCL_DROPDOWN,
    ACCY_OCL_RATING,
    ACCY_OCL_SINGLE_LINE,
    ACCY_OCL_VALUE,
    ACCY_ST_DESC_CHECKED,
    ACCY_ST_DESC_LOADING,
    ACCY_ST_DESC_UNCHECKED,

    // Home.
    HOME_TITLE,
    HOME_SECTION_BIG_IMAGE,
    HOME_SECTION_GRID_IMAGES,
    HOME_EMPTY,
    HOME_ALL_ERROR,

    // Browse.
