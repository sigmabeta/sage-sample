    APP_NAME,

    // Navigation shell.
    NAV_HOME,
    NAV_BROWSE,
    NAV_SEARCH,
    NAV_LIST_ITEMS,
    NAV_LIST_ITEMS_WITH_IMAGES,
    NAV_GRID_OF_IMAGES,
    NAV_CONTENT_DETAIL,
    NAV_SETTINGS,
    NAV_OPEN_SETTINGS_DESCRIPTION,
    NAV_BACK_DESCRIPTION,

