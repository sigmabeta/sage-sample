// Build identity for Settings > About; the JS twin of apps/jvm's generated build-info file.
val webBuildInfoDir = layout.buildDirectory.dir("generated/webBuildInfo")
val generateWebBuildInfo = tasks.register("generateWebBuildInfo") {
    description = "Generates WebBuildInfo.kt from git (or neutral web defaults)."
    group = "build"
    val outputDir = webBuildInfoDir
    val repoRoot = rootProject.layout.projectDirectory.asFile.absolutePath
    outputs.dir(outputDir)
    outputs.upToDateWhen { false }
    doLast {
        fun git(vararg args: String): String? = try {
            val process = ProcessBuilder(listOf("git") + args)
                .directory(File(repoRoot))
                .redirectErrorStream(true)
                .start()
            val output = process.inputStream.bufferedReader().use { it.readText() }.trim()
            if (process.waitFor() == 0) output.ifBlank { null } else null
        } catch (_: Exception) {
            null
        }

        fun kotlinString(value: String): String =
            value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

        val versionName = git("describe", "--tags", "--always", "--dirty") ?: "0.0.0-web"
        val versionCode = git("rev-list", "--count", "HEAD")?.toIntOrNull() ?: 1
        val branch = git("rev-parse", "--abbrev-ref", "HEAD") ?: "web"
        val commit = git("rev-parse", "--short", "HEAD") ?: "unknown"
        val buildTimeMs = git("log", "-1", "--format=%ct")?.toLongOrNull()?.times(1000L)

        val source = buildString {
            appendLine("package net.sigmabeta.sage.sample.js")
            appendLine()
            appendLine("/** Generated by :apps:js:generateWebBuildInfo — do not edit. */")
            appendLine("internal object WebBuildInfo {")
            appendLine("    const val VERSION_NAME: String = \"${kotlinString(versionName)}\"")
            appendLine("    const val VERSION_CODE: Int = $versionCode")
            appendLine("    val BUILD_TIME_MS: Long? = ${buildTimeMs?.let { "${it}L" } ?: "null"}")
            appendLine("    const val BUILD_BRANCH: String = \"${kotlinString(branch)}\"")
            appendLine("    const val BUILD_COMMIT: String = \"${kotlinString(commit)}\"")
            appendLine("}")
        }
        val target = File(outputDir.get().asFile, "net/sigmabeta/sage/sample/js/WebBuildInfo.kt")
        target.parentFile.mkdirs()
        target.writeText(source)
    }
}

